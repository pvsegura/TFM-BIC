import { RECALL_GRADES } from "@verbysia/domain";
import { sql } from "drizzle-orm";
import {
  check,
  index,
  integer,
  pgTable,
  primaryKey,
  real,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

import { users } from "../../identity/db/schema.js";

const GRADES_SQL = sql.raw(RECALL_GRADES.map((g) => `'${g}'`).join(", "));
const ITEM_ID_SQL = sql.raw(`'^[a-z][a-z0-9]*(-[a-z0-9]+)*$'`);

/**
 * One memory-trainer card per learner per vocabulary entry (the entry itself is a content file,
 * so `vocabulary_item_id` is validated text, not a foreign key — same rule as `user_vocabulary`).
 * `version` is bumped on every review: a review is applied with `WHERE version = expected`, so
 * two devices answering the same card at once cannot both move it (the loser re-reads and retries).
 */
export const memoryCards = pgTable(
  "memory_cards",
  {
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    vocabularyItemId: text("vocabulary_item_id").notNull(),
    repetitions: integer("repetitions").notNull(),
    intervalDays: integer("interval_days").notNull(),
    ease: real("ease").notNull(),
    dueAt: timestamp("due_at", { withTimezone: true }).notNull(),
    lapses: integer("lapses").notNull(),
    version: integer("version").notNull(),
    lastReviewedAt: timestamp("last_reviewed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
  },
  (t) => [
    primaryKey({ name: "memory_cards_pk", columns: [t.userId, t.vocabularyItemId] }),
    index("memory_cards_due_idx").on(t.userId, t.dueAt),
    check(
      "memory_cards_item_id_valid",
      sql`char_length(${t.vocabularyItemId}) <= 64 AND ${t.vocabularyItemId} ~ ${ITEM_ID_SQL}`,
    ),
    check("memory_cards_ease_min", sql`${t.ease} >= 1.3`),
    check(
      "memory_cards_counts_non_negative",
      sql`${t.repetitions} >= 0 AND ${t.intervalDays} >= 0 AND ${t.lapses} >= 0`,
    ),
  ],
);

/**
 * Every answer, append-only — the log statistics are computed from, and what a future FSRS
 * migration would be fitted on. `client_review_id` is generated by the browser per answer; it is
 * unique per learner, so a retried request after a dropped connection is recorded once.
 */
export const memoryReviews = pgTable(
  "memory_reviews",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    vocabularyItemId: text("vocabulary_item_id").notNull(),
    clientReviewId: uuid("client_review_id").notNull(),
    grade: text("grade", { enum: RECALL_GRADES }).notNull(),
    usedHint: integer("used_hint").notNull(),
    previousIntervalDays: integer("previous_interval_days").notNull(),
    intervalDays: integer("interval_days").notNull(),
    ease: real("ease").notNull(),
    reviewedAt: timestamp("reviewed_at", { withTimezone: true }).notNull(),
  },
  (t) => [
    uniqueIndex("memory_reviews_client_unique").on(t.userId, t.clientReviewId),
    index("memory_reviews_user_time_idx").on(t.userId, t.reviewedAt),
    check("memory_reviews_grade_valid", sql`${t.grade} IN (${GRADES_SQL})`),
    check("memory_reviews_hint_flag", sql`${t.usedHint} IN (0, 1)`),
  ],
);
